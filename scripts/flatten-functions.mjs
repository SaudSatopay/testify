// Bundles each edge function + the _shared modules into ONE self-contained
// file so it can be deployed through the Supabase dashboard editor (which
// has no cross-function _shared folder). Import statements for local files
// are stripped (the code is concatenated in dependency order); npm imports
// are deduplicated and hoisted.
import { mkdir, readFile, writeFile, readdir } from "node:fs/promises";
import { join } from "node:path";

const FN_DIR = "supabase/functions";
const OUT_DIR = "supabase/dist-dashboard";

// Topological order of the shared modules (dependencies first).
const SHARED_ORDER = [
  "_shared/cors.ts",
  "_shared/response.ts",
  "_shared/supabase.ts",
  "_shared/auth.ts",
  "_shared/rateLimit.ts",
  "_shared/validate.ts",
  "_shared/audit.ts",
  "_shared/ai/types.ts",
  "_shared/ai/prompts.ts",
  "_shared/ai/openai.ts",
  "_shared/ai/anthropic.ts",
  "_shared/ai/index.ts",
];

const IMPORT_RE = /^import\s[\s\S]*?from\s+["']([^"']+)["'];?[ \t]*$/gm;

/** Split a file into { npmImports: Map<module, {named:Set, types:Set}>, body } */
function extractImports(source) {
  const npm = new Map();
  const body = source.replace(IMPORT_RE, (statement, specifier) => {
    if (specifier.startsWith(".")) return ""; // local import — code is inlined
    const entry = npm.get(specifier) ?? { named: new Set(), types: new Set() };
    const isTypeOnly = /^import\s+type\b/.test(statement);
    const braceMatch = statement.match(/\{([\s\S]*?)\}/);
    if (braceMatch) {
      for (let raw of braceMatch[1].split(",")) {
        raw = raw.trim();
        if (!raw) continue;
        if (raw.startsWith("type ")) entry.types.add(raw.slice(5).trim());
        else if (isTypeOnly) entry.types.add(raw);
        else entry.named.add(raw);
      }
    }
    npm.set(specifier, entry);
    return "";
  });
  return { npm, body };
}

function mergeNpm(target, source) {
  for (const [specifier, entry] of source) {
    const existing = target.get(specifier) ?? { named: new Set(), types: new Set() };
    entry.named.forEach((n) => existing.named.add(n));
    entry.types.forEach((t) => existing.types.add(t));
    target.set(specifier, existing);
  }
}

function renderNpmImports(npm) {
  const lines = [];
  for (const [specifier, { named, types }] of npm) {
    // A name imported as both value and type only needs the value import.
    const typeOnly = [...types].filter((t) => !named.has(t));
    if (named.size > 0) lines.push(`import { ${[...named].sort().join(", ")} } from "${specifier}";`);
    if (typeOnly.length > 0) lines.push(`import type { ${typeOnly.sort().join(", ")} } from "${specifier}";`);
  }
  return lines.join("\n");
}

await mkdir(OUT_DIR, { recursive: true });

// Per-module tweaks that make concatenation collision-free.
function adjustSharedBody(rel, body) {
  // Bare re-export statements (ai/index.ts re-exports types) conflict with
  // the original declarations once everything lives in one module.
  body = body.replace(/^export\s+(?:type\s+)?\{[^}]*\};?[ \t]*$/gm, "");
  if (rel.endsWith("ai/openai.ts")) {
    body = body.replaceAll("REQUEST_TIMEOUT_MS", "OPENAI_REQUEST_TIMEOUT_MS");
  }
  if (rel.endsWith("ai/anthropic.ts")) {
    body = body.replaceAll("REQUEST_TIMEOUT_MS", "ANTHROPIC_REQUEST_TIMEOUT_MS");
  }
  return body;
}

const sharedParts = [];
const sharedNpm = new Map();
for (const rel of SHARED_ORDER) {
  const source = await readFile(join(FN_DIR, rel), "utf8");
  const { npm, body } = extractImports(source);
  mergeNpm(sharedNpm, npm);
  sharedParts.push(`// ===== inlined ${rel} =====\n${adjustSharedBody(rel, body).trim()}\n`);
}

const entries = (await readdir(FN_DIR, { withFileTypes: true }))
  .filter((e) => e.isDirectory() && !e.name.startsWith("_"))
  .map((e) => e.name);

for (const name of entries) {
  const source = await readFile(join(FN_DIR, name, "index.ts"), "utf8");
  const { npm, body } = extractImports(source);
  const allNpm = new Map();
  mergeNpm(allNpm, sharedNpm);
  mergeNpm(allNpm, npm);
  const bundle = [
    `// ${name} — dashboard-deployable bundle (auto-generated by scripts/flatten-functions.mjs)`,
    `// Source of truth: supabase/functions/${name}/index.ts + _shared modules.`,
    renderNpmImports(allNpm),
    "",
    sharedParts.join("\n"),
    `// ===== function: ${name} =====`,
    body.trim(),
    "",
  ].join("\n");
  await writeFile(join(OUT_DIR, `${name}.ts`), bundle, "utf8");
  console.log(`bundled ${name}.ts (${bundle.length} chars)`);
}
console.log("done");
